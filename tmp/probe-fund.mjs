const UA = 'Mozilla/5.0';
const r1 = await fetch('https://fc.yahoo.com/', { headers: { 'User-Agent': UA } });
const setCookie = r1.headers.getSetCookie ? r1.headers.getSetCookie() : [r1.headers.get('set-cookie')];
console.log('fc.yahoo.com status:', r1.status);
const cookie = (setCookie ?? []).map(c => c.split(';')[0]).filter(Boolean).join('; ');
console.log('cookie prefix:', cookie.slice(0, 50));
const r2 = await fetch('https://query1.finance.yahoo.com/v1/test/getcrumb', { headers: { 'User-Agent': UA, Cookie: cookie } });
const crumb = await r2.text();
console.log('crumb status:', r2.status, 'crumb:', JSON.stringify(crumb));
const mods = 'price,summaryDetail,defaultKeyStatistics,financialData,assetProfile';
const url = `https://query1.finance.yahoo.com/v10/finance/quoteSummary/AAPL?modules=${mods}&crumb=${encodeURIComponent(crumb)}`;
const r3 = await fetch(url, { headers: { 'User-Agent': UA, Cookie: cookie, Accept: 'application/json' } });
console.log('quoteSummary status:', r3.status);
const j = await r3.json();
const res = j.quoteSummary?.result?.[0];
console.log('module keys:', Object.keys(res ?? {}));
console.log(JSON.stringify(res, null, 2).slice(0, 6000));
